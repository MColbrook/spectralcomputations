function   y1 = thet2 (tau)
%--------------------------------------------------
%
n     =     200;
q     =     exp(i*pi*tau);
z     =     0;
y1    =     0;
%--------------------------------------------------
for k=0:n
    y1 = y1 + (q^(k^2+k))*cos((2*k+1).*z);
end
y  = 2*q^(1/4).*y1;
%--------------------------------------------------